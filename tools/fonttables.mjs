// Generates pdf/font/tables.go from pdf.js (Apache-2.0): glyph list, base
// encodings, standard 14 font metrics and font name aliases.
//   node tools/fonttables.mjs > pdf/font/tables.go && gofmt -w pdf/font/tables.go
import { readFileSync } from 'node:fs'

const src = readFileSync(new URL('../web/node_modules/pdfjs-dist/build/pdf.worker.mjs', import.meta.url), 'utf8')
const lines = src.split('\n')

const getLookupTableFactory = (init) => {
  let t
  return () => {
    if (!t) {
      t = Object.create(null)
      init(t)
    }
    return t
  }
}

// Returns the source of `const name = ...;` up to the matching close.
function grab(name) {
  const start = lines.findIndex((l) => l.startsWith(`const ${name} = `))
  if (start < 0) throw new Error(`not found: ${name}`)
  if (lines[start].endsWith(';')) return lines[start]
  let end = start + 1
  while (lines[end] !== '});') end++
  return lines.slice(start, end + 1).join('\n')
}

const get = (name) => new Function('getLookupTableFactory', `${grab(name)}; return ${name};`)(getLookupTableFactory)

const encodings = {
  standard: get('StandardEncoding'),
  winAnsi: get('WinAnsiEncoding'),
  macRoman: get('MacRomanEncoding'),
  macExpert: get('MacExpertEncoding'),
  symbol: get('SymbolSetEncoding'),
  zapfDingbats: get('ZapfDingbatsEncoding'),
}
const glyphs = { ...get('getGlyphsUnicode')(), ...get('getDingbatsGlyphsUnicode')() }
const metrics = get('getMetrics')()
const aliases = get('getStdFontMap')()

const q = JSON.stringify
let out = `// Code generated by tools/fonttables.mjs from pdf.js (Apache-2.0). DO NOT EDIT.

package font

`
for (const [name, enc] of Object.entries(encodings)) {
  out += `var ${name}Encoding = [256]string{${enc.map(q).join(',')}}\n\n`
}
out += 'var glyphUnicode = map[string]rune{\n'
for (const [k, v] of Object.entries(glyphs)) if (typeof v === 'number') out += `${q(k)}:${v},\n`
out += '}\n\n'
out += 'var stdWidths = map[string]map[string]uint16{\n'
for (const [font, m] of Object.entries(metrics)) {
  if (typeof m === 'number') continue // Courier family: fixed 600
  out += `${q(font)}: {`
  out += Object.entries(m())
    .map(([g, w]) => `${q(g)}:${w}`)
    .join(',')
  out += '},\n'
}
out += '}\n\n'
out += 'var stdAliases = map[string]string{\n'
for (const [k, v] of Object.entries(aliases)) out += `${q(k)}:${q(v)},\n`
out += '}\n'
process.stdout.write(out)
